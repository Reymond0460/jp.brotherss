/**
 * @param {keyof typeof PATHS} name
 * @param {{size?: number, className?: string}} [options]
 */
export function icon(name, { size = 20, className = '' } = {}) {
  const svg = svgEl('svg', {
    class: `icon ${className}`.trim(),
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': 1.8,
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    'aria-hidden': 'true',
    focusable: 'false',
  });
  // Contenido controlado por nosotros (constante de arriba), no hay entrada de usuario.
  svg.innerHTML = PATHS[name] ?? '';
  return svg;
}

/** Reemplaza cada <span data-icon="nombre" data-size="18"> por su SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((node) => {
    const size = Number(node.dataset.size) || 20;
    node.replaceWith(icon(node.dataset.icon, { size, className: node.className }));
  });
}
